/* ===========================================================
   One-off migration: products.js + product-data.js  →  SQL

   Reads the existing catalogue files and writes a seed file you
   paste into the Supabase SQL Editor. Nothing is lost: variants,
   supplier costs, review quotes and merchandising flags all carry
   across.

   Run:  node scripts/migrate-products.js
   Out:  supabase/seed.sql

   Safe to re-run — the generated SQL upserts on sku, so running
   the seed twice won't create duplicates.
   =========================================================== */

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");

// --- load the catalogue files in a sandbox -------------------
// They're plain scripts declaring globals, not modules, so we
// evaluate them in a VM context and pull the globals back out.
function loadCatalogue() {
  const ctx = {};
  vm.createContext(ctx);
  const src =
    fs.readFileSync(path.join(ROOT, "products.js"), "utf8") +
    "\n" +
    fs.readFileSync(path.join(ROOT, "product-data.js"), "utf8") +
    "\n; this.__PRODUCTS = PRODUCTS;" +
    "  this.__DATA = PRODUCT_DATA;" +
    "  this.__MYSTERY = MYSTERY_IDS;" +
    "  this.__NEWDROP = NEW_DROP_IDS;";
  vm.runInContext(src, ctx);
  return {
    products: ctx.__PRODUCTS,
    data: ctx.__DATA,
    mystery: ctx.__MYSTERY || [],
    newDrop: ctx.__NEWDROP || []
  };
}

// --- SQL escaping --------------------------------------------
function sqlStr(v) {
  if (v === null || v === undefined || v === "") return "null";
  return "'" + String(v).replace(/'/g, "''") + "'";
}

function sqlNum(v) {
  if (v === null || v === undefined || v === "" || Number.isNaN(Number(v))) return "null";
  return Number(v);
}

function sqlBool(v) {
  return v ? "true" : "false";
}

// text[] literal
function sqlTextArray(arr) {
  if (!arr || !arr.length) return "'{}'";
  const inner = arr.map(s => '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"');
  return "'{" + inner.join(",") + "}'";
}

// jsonb literal
function sqlJson(obj) {
  if (!obj) return "'[]'::jsonb";
  return sqlStr(JSON.stringify(obj)) + "::jsonb";
}

// --- build ----------------------------------------------------
function build() {
  const { products, data, mystery, newDrop } = loadCatalogue();

  const lines = [];
  lines.push("-- ===========================================================");
  lines.push("-- Squishy Society — seed data");
  lines.push("-- Generated by scripts/migrate-products.js");
  lines.push("-- Source: products.js + product-data.js at time of migration");
  lines.push("--");
  lines.push("-- Paste into: Supabase dashboard → SQL Editor → New query → Run");
  lines.push("-- Safe to re-run (upserts on sku).");
  lines.push("-- ===========================================================");
  lines.push("");
  lines.push("begin;");
  lines.push("");

  let variantCount = 0;

  products.forEach((p, i) => {
    const d = data[p.id] || {};
    const sup = d.supplier || {};
    const opts = d.options || {};

    lines.push(`-- ${p.sku || p.id} · ${p.name}`);
    lines.push("insert into products (");
    lines.push("  sku, name, category, description,");
    lines.push("  price, supplier_cost, shipping_cost,");
    lines.push("  supplier_name, supplier_url,");
    lines.push("  image, gallery,");
    lines.push("  status,");
    lines.push("  source_rating, source_reviews, source_orders, source_tags, source_quotes,");
    lines.push("  is_mystery, is_new_drop, sort_order");
    lines.push(") values (");
    lines.push(`  ${sqlStr(p.id)}, ${sqlStr(p.name)}, ${sqlStr(p.category)}, ${sqlStr(p.description)},`);
    lines.push(`  ${sqlNum(p.price)}, ${sqlNum(p.supplierCost)}, ${sqlNum(p.shippingCost || 0)},`);
    // Everything sourced so far comes from AliExpress sellers.
    lines.push(`  ${sqlStr(p.sourceUrl ? "AliExpress" : null)}, ${sqlStr(p.sourceUrl)},`);
    lines.push(`  ${sqlStr(p.image)}, ${sqlTextArray(d.gallery)},`);
    lines.push(`  'active',`);
    lines.push(
      `  ${sqlNum(sup.rating != null ? sup.rating : p.sourceRating)}, ` +
      `${sqlNum(sup.reviews)}, ${sqlStr(p.sourceOrders)}, ` +
      `${sqlTextArray(sup.tags)}, ${sqlJson(sup.quotes || [])},`
    );
    lines.push(
      `  ${sqlBool(mystery.includes(p.id))}, ${sqlBool(newDrop.includes(p.id))}, ${i * 10}`
    );
    lines.push(")");
    lines.push("on conflict (sku) do update set");
    lines.push("  name = excluded.name,");
    lines.push("  category = excluded.category,");
    lines.push("  description = excluded.description,");
    lines.push("  price = excluded.price,");
    lines.push("  supplier_cost = excluded.supplier_cost,");
    lines.push("  shipping_cost = excluded.shipping_cost,");
    lines.push("  supplier_name = excluded.supplier_name,");
    lines.push("  supplier_url = excluded.supplier_url,");
    lines.push("  image = excluded.image,");
    lines.push("  gallery = excluded.gallery,");
    lines.push("  source_rating = excluded.source_rating,");
    lines.push("  source_reviews = excluded.source_reviews,");
    lines.push("  source_orders = excluded.source_orders,");
    lines.push("  source_tags = excluded.source_tags,");
    lines.push("  source_quotes = excluded.source_quotes,");
    lines.push("  is_mystery = excluded.is_mystery,");
    lines.push("  is_new_drop = excluded.is_new_drop,");
    lines.push("  sort_order = excluded.sort_order;");
    lines.push("");

    // ---- variants ----
    // Only products with real per-variant pricing get variant rows.
    // Options with no price data are just descriptive, so they'd add
    // noise without adding information.
    const values = opts.values || [];
    const prices = opts.prices || null;
    const costs = opts.variantCost || null;

    if (values.length && prices) {
      lines.push(`-- variants for ${p.id}`);
      lines.push(`delete from product_variants where product_id = (select id from products where sku = ${sqlStr(p.id)});`);
      values.forEach((label, vi) => {
        if (prices[label] == null) return;
        variantCount++;
        lines.push("insert into product_variants (product_id, label, variant_cost, price, sort_order)");
        lines.push(
          `select id, ${sqlStr(label)}, ${sqlNum(costs ? costs[label] : null)}, ` +
          `${sqlNum(prices[label])}, ${vi * 10} from products where sku = ${sqlStr(p.id)};`
        );
      });
      lines.push("");
    }
  });

  lines.push("commit;");
  lines.push("");
  lines.push(`-- ${products.length} products, ${variantCount} priced variants`);
  lines.push("");

  const outPath = path.join(ROOT, "supabase", "seed.sql");
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, lines.join("\n"));

  console.log(`Wrote ${path.relative(ROOT, outPath)}`);
  console.log(`  ${products.length} products`);
  console.log(`  ${variantCount} priced variants`);

  // A quick summary so it's obvious if something didn't carry across.
  const noUrl = products.filter(p => !p.sourceUrl).map(p => p.id);
  if (noUrl.length) {
    console.log(`  note: ${noUrl.length} products still have no supplier URL (${noUrl.join(", ")})`);
  }
}

build();
